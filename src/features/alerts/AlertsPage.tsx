/* ==========================================================================
   ALERTS CENTRE  (/alerts): reminders, overdue items and escalations.
   Alerts are generated by rules in src/api/endpoints.ts → getAlerts().
   ========================================================================== */
import { useState } from 'react';
import { Link } from 'react-router-dom';
import { useTranslation } from 'react-i18next';
import type { Icon } from '@phosphor-icons/react';
import { ArrowFatLinesUp, BellSimpleSlash, Checks, Clock, FileText, Heartbeat, Hourglass, UserPlus, WarningOctagon } from '@phosphor-icons/react';
import type { Alert } from '@/types/domain';
import { useAlerts, useMarkAlertsRead } from '@/api/hooks';
import { formatShort } from '@/lib/dates';
import { Button, Card, EmptyState, PageHeader, Segmented, SkeletonRows } from '@/ui';
import { cx } from '@/lib/cx';
import s from './AlertsPage.module.css';

const ICON: Record<Alert['kind'], Icon> = {
  escalation: ArrowFatLinesUp,
  overdue: WarningOctagon,
  health_changed: Heartbeat,
  report_due: FileText,
  due_soon: Clock,
  stale: Hourglass,
  assigned: UserPlus,
};

export function AlertsPage() {
  const { t } = useTranslation();
  const { data, isLoading } = useAlerts();
  const markRead = useMarkAlertsRead();
  const [view, setView] = useState<'unread' | 'all'>('unread');

  const all = data ?? [];
  const unread = all.filter((a) => !a.read);
  const list = view === 'unread' ? unread : all;

  return (
    <>
      <PageHeader
        eyebrow={t('nav.alerts')}
        title={t('alerts.title')}
        lede={t('alerts.lede')}
        actions={
          unread.length > 0 && (
            <Button icon={<Checks size={18} />} onClick={() => markRead.mutate(unread.map((a) => a.id))}>
              {t('alerts.markAll')}
            </Button>
          )
        }
      />

      <div className={s.bar}>
        <Segmented
          label={t('alerts.view')}
          value={view}
          onChange={setView}
          options={[
            { value: 'unread', label: t('alerts.unread'), count: unread.length },
            { value: 'all', label: t('alerts.all'), count: all.length },
          ]}
        />
      </div>

      <Card flush>
        {isLoading ? (
          <SkeletonRows rows={6} />
        ) : !list.length ? (
          <EmptyState icon={<BellSimpleSlash size={40} />} title={t('alerts.none')}>
            {t('alerts.noneHint')}
          </EmptyState>
        ) : (
          <ul className={s.list}>
            {list.map((a) => {
              const I = ICON[a.kind];
              return (
                <li key={a.id} className={cx(s.item, s[a.kind], a.read && s.read)}>
                  <span className={s.icon}>
                    <I size={20} weight="fill" />
                  </span>
                  <div className={s.body}>
                    <div className={s.kind}>{t(`alerts.kind.${a.kind}`)}</div>
                    <Link
                      to={`/projects/${a.projectId}${a.itemId ? '/deliverables' : ''}`}
                      className={s.title}
                      onClick={() => !a.read && markRead.mutate([a.id])}
                    >
                      {a.title}
                    </Link>
                    <div className={s.detail}>
                      {t(`alerts.detail.${a.kind}`, { detail: a.detail })}
                    </div>
                  </div>
                  <span className={`mono ${s.when}`}>{formatShort(a.createdAt)}</span>
                  {!a.read && (
                    <button className={s.dismiss} onClick={() => markRead.mutate([a.id])} title={t('alerts.markRead')} aria-label={t('alerts.markRead')}>
                      <span />
                    </button>
                  )}
                </li>
              );
            })}
          </ul>
        )}
      </Card>

      <p className={s.rules}>{t('alerts.rules')}</p>
    </>
  );
}
